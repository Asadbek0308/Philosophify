const ERA_NAME = Object.fromEntries(TIMELINE_ERAS.map((e) => [e.id, e.name]));

export const formatYear = (y, approx = false) => {
  const base = y < 0 ? `${-y} BC` : `${y} AD`;
  return approx ? `c. ${base}` : base;
};

// Stable, readable ids (used in shareable links: /timeline?m=-399-the-trial-and-death-of-socrates)
const slugify = (s) =>
  s
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[’'“”]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60);

export const TIMELINE_DATA = RAW.map((r, i) => ({ r, i }))
  .sort((a, b) => a.r.y - b.r.y || a.i - b.i)
  .map(({ r }) => ({
    id: `${r.y}-${slugify(r.title)}`,
    year: r.y,
    approx: !!r.c,
    yearDisplay: formatYear(r.y, r.c),
    era: r.era,
    eraName: ERA_NAME[r.era],
    title: r.title,
    thinker: r.thinker,
    school: r.school,
    location: r.loc,
    axiom: r.q ? `“${r.q}”` : null,
    description: r.d,
    paradigmShift: r.shift,
    influence: r.legacy,
    tags: r.tags,
    mapNode: MAP_NODE_BY_THINKER[r.thinker] || null,
  }));